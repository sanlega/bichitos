    /// A character's cell: `height` rows of the same width, or nil if the font lacks it.
    /// Accented letters are their base letter plus a mark: acute, diaeresis or tilde.
    static func cell(_ c: Character) -> [[Bool]]? {
        let scalars = Array(String(c).decomposedStringWithCanonicalMapping.unicodeScalars)
        guard let first = scalars.first, let rows = glyphs[Character(first)] else { return nil }
        let marks = scalars.dropFirst().map(\.value)
        guard marks.allSatisfy({ [0x301, 0x308, 0x303].contains($0) }) else { return nil }
        var width = rows[0].count
        var g = Array(repeating: Array(repeating: false, count: maxWidth), count: height)
        for (y, row) in rows.enumerated() {
            for (x, p) in row.enumerated() { g[top + y][x] = p == "#" }
        }
        let upper = Character(first).isUppercase
        if !marks.isEmpty, first == "i" || first == "j" { g[top] = g[top].map { _ in false } } // dotless under the mark
        // Lowercase marks sit over the x-height with a row between; capital marks sit right on the cap line.
        let y0 = upper ? 0 : 1
        func dot(_ x: Int, _ y: Int) { g[y][x] = true; width = max(width, x + 1) }
        for mark in marks {
            switch mark {
            case 0x301: // acute
                let x = (width - 1) / 2
                dot(x + 1, y0); dot(x, y0 + 1)
            case 0x308: // diaeresis
                dot(0, y0 + 1); dot(max(width - 1, 2), y0 + 1)
            default: // tilde
                let (hi, lo) = width >= 5 ? ([1, 2, 4], [0, 3]) : ([1, 3], [0, 2])
                for x in hi { dot(x, y0) }
                for x in lo { dot(x, y0 + 1) }
            }
        }
        return g.map { Array($0.prefix(width)) }
    }

    static func covers(_ text: String) -> Bool { text.allSatisfy { cell($0) != nil } }

    /// `text` in one row of cells a column apart, inside a 1 px margin. 1 is ink, 2 the light outline around it.
    /// Characters the font lacks (a typed name can have any) are drawn as '?'.
    static func grid(_ text: String) -> PixelGrid {
        let cells = text.map { cell($0) ?? cell("?")! }
        let width = cells.reduce(0) { $0 + $1[0].count } + max(cells.count - 1, 0) + 2
        var g = PixelGrid(width: width, height: height + 2)
        var x0 = 1
        for c in cells {
            for (y, row) in c.enumerated() {
                for (x, p) in row.enumerated() where p { g[x0 + x, 1 + y] = 1 }
            }
            x0 += c[0].count + 1
        }
        for y in 0..<g.height {
            for x in 0..<g.width where g[x, y] == 0 {
                if [(1, 0), (-1, 0), (0, 1), (0, -1)].contains(where: { g[x + $0.0, y + $0.1] == 1 }) { g[x, y] = 2 }
            }
        }
        return g
    }

    /// Ink, and white at 60% for the outline (premultiplied, as `Sprites.image` expects).
    static let palette = Palette(name: "font", colors: [
        RGBA(r: 0, g: 0, b: 0, a: 0), RGBA(hex: Palette.pupil), RGBA(r: 153, g: 153, b: 153, a: 153),
    ])
}
